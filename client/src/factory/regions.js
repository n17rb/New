const norm = (s) => String(s || "").trim().replace(/\s+/g, " ").replace(/[أإآ]/g, "ا").replace(/ة$/, "ه").replace(/ى$/, "ي").replace(/ّ/g, "");
const TOWN_INDEX = new Map(Object.entries(TOWNS).map(([k, v]) => [norm(k), v]));
const GOV_INDEX = new Map(Object.keys(GOVERNORATES).map((g) => [norm(g), g]));
const DISTRICT_INDEX = new Map(Object.entries(GOVERNORATES).flatMap(([g, ds]) => ds.map((d) => [norm(d.replace(/^قصبة /, "")), [g, d]])));

// من اسم المنطقة اللي كتبه المستخدم: وين بتتبع؟
export function inferRegion(city) {
  const n = norm(city);
  if (!n) return { governorate: null, district: null };
  const t = TOWN_INDEX.get(n);
  if (t) return { governorate: t[0], district: t[1] };
  const d = DISTRICT_INDEX.get(n);
  if (d) return { governorate: d[0], district: d[1] };
  const g = GOV_INDEX.get(n);
  if (g) return { governorate: g, district: GOVERNORATES[g][0] };
  return { governorate: null, district: null };
}

export function validRegion(governorate, district) {
  const g = GOVERNORATES[governorate] ? governorate : null;
  return { governorate: g, district: g && district && String(district).trim() ? String(district).trim().slice(0, 60) : null };
}
