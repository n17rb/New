const DEFS = Object.fromEntries(TEMPLATE_DEFS.map((d) => [d.key, d]));
const STORE_KEY = "msg_templates";

let overrides = (() => {
  try { return JSON.parse(localStorage.getItem(STORE_KEY) || "{}") || {}; } catch { return {}; }
})();

export function setTemplates(obj) {
  overrides = obj && typeof obj === "object" ? obj : {};
  try { localStorage.setItem(STORE_KEY, JSON.stringify(overrides)); } catch { /* تجاهل */ }
}
export function getTemplate(key) {
  return overrides[key] || DEFS[key]?.text || "";
}
export function isCustomized(key) {
  return !!overrides[key];
}

// تعبئة النص: {الاسم} ← القيمة. السطور اللي فضيت بسبب متغير فاضي بتنشال
export function fillTemplate(text, vars) {
  const all = { "المحل": shopName(), ...vars };
  const lines = text.split("\n").map((line) => {
    const hadVar = /\{[^}\n]+\}/.test(line);
    const out = line.replace(/\{([^}\n]+)\}/g, (m, name) => {
      const v = all[name.trim()];
      return v == null ? "" : String(v);
    });
    return hadVar && !out.trim() ? null : out;
  });
  return lines.filter((l) => l !== null).join("\n").replace(/\n{3,}/g, "\n\n").trim();
}

export function renderMessage(key, vars = {}) {
  return fillTemplate(getTemplate(key), vars);
}

export function sampleMessage(key, text) {
  const d = DEFS[key];
  return fillTemplate(text ?? getTemplate(key), { "الاسم": "أبو أحمد", ...(d?.sample || {}) });
}

export function waLink(phone, text) {
  return `https://wa.me/${phone}?text=${encodeURIComponent(text)}`;
}
